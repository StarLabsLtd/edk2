#include <stdint.h>
#include <stdio.h>

int main(int argc, char **argv)
{
	static const uint8_t depex[] = {
		0x3a, 0x00, 0x00, 0x13,
		0x02, 0xa9, 0x4f, 0x64, 0x8f, 0x50, 0xe8, 0xb1, 0x4d,
		0x9c, 0xe2, 0x0b, 0x44, 0x69, 0x8e, 0x8d, 0xa4,
		0x02, 0xe1, 0xb4, 0xdf, 0xb7, 0x2f, 0x05, 0x9f, 0x44,
		0x87, 0xbe, 0x98, 0x18, 0xfc, 0x91, 0xb7, 0x33,
		0x02, 0xf6, 0xf0, 0xa3, 0x13, 0x4a, 0x26, 0xf0, 0x3e,
		0xf2, 0xe0, 0xde, 0xc5, 0x12, 0x34, 0x2f, 0x34,
		0x03, 0x03, 0x08
	};
	FILE *output;

	if (argc != 2)
		return 1;
	output = fopen(argv[1], "wb");
	if (output == NULL || fwrite(depex, 1, sizeof(depex), output) != sizeof(depex) ||
	    fclose(output) != 0)
		return 1;
	return 0;
}
