/* Emit the exact admitted PchSmiDispatchSmm MM DEPEX section. */

#include <stdint.h>
#include <stdio.h>

int main(int argc, char **argv)
{
	static const uint8_t depex[] = {
		0x4c, 0x00, 0x00, 0x1c,
		0x02, 0x97, 0x6b, 0x34, 0xeb, 0x5f, 0x97, 0x9f, 0x4a,
		0x8b, 0x22, 0xf8, 0xe9, 0x2b, 0xb3, 0xd5, 0x69,
		0x02, 0xf6, 0xf0, 0xa3, 0x13, 0x4a, 0x26, 0xf0, 0x3e,
		0xf2, 0xe0, 0xde, 0xc5, 0x12, 0x34, 0x2f, 0x34,
		0x02, 0xb7, 0xbf, 0xcc, 0xf4, 0xe0, 0xf6, 0xfd, 0x47,
		0x9d, 0xd4, 0x10, 0xa8, 0xf1, 0x50, 0xc1, 0x91,
		0x02, 0x74, 0x2b, 0x70, 0xc2, 0x0c, 0x80, 0x31, 0x41,
		0x87, 0x46, 0x8f, 0xb5, 0xb8, 0x9c, 0xe4, 0xac,
		0x03, 0x03, 0x03, 0x08
	};
	FILE *output;

	if (argc != 2)
		return 1;
	output = fopen(argv[1], "wb");
	if (output == NULL || fwrite(depex, 1, sizeof(depex), output) != sizeof(depex) ||
	    fclose(output) != 0)
		return 1;
	return 0;
}
