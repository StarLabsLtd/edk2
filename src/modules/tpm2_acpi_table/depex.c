/* Emit the exact admitted Tpm2AcpiTableDxe DXE DEPEX section. */

#include <stdint.h>
#include <stdio.h>

int main(int argc, char **argv)
{
	static const uint8_t depex[] = {
		0x4c, 0x00, 0x00, 0x13,
		0x02, 0xdd, 0x6b, 0xe0, 0xff, 0x07, 0x61, 0xa6, 0x46,
		0x7b, 0xb2, 0x5a, 0x9c, 0x7e, 0xc5, 0x27, 0x5c,
		0x02, 0x8e, 0x08, 0x97, 0xeb, 0xdf, 0xcf, 0xc6, 0x49,
		0xbe, 0x4b, 0xd9, 0x06, 0xa5, 0xb2, 0x0e, 0x86,
		0x02, 0x6c, 0x76, 0x7f, 0x60, 0x55, 0x74, 0xbe, 0x42,
		0x93, 0x0b, 0xe4, 0xd7, 0x6d, 0xb2, 0x72, 0x0f,
		0x02, 0xf6, 0xf0, 0xa3, 0x13, 0x4a, 0x26, 0xf0, 0x3e,
		0xf2, 0xe0, 0xde, 0xc5, 0x12, 0x34, 0x2f, 0x34,
		0x03, 0x03, 0x03, 0x08
	};
	FILE *output;

	if (argc != 2)
		return 1;
	output = fopen(argv[1], "wb");
	if (output == NULL || fwrite(depex, 1, sizeof(depex), output) != sizeof(depex) ||
	    fclose(output) != 0)
		return 1;
	return 0;
}
