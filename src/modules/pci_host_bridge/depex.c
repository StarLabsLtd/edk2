#include <stdint.h>
#include <stdio.h>

int main(int argc, char **argv)
{
	static const uint8_t section[] = {
		0x3a, 0x00, 0x00, 0x13,
		0x02, 0x91, 0xf1, 0x61, 0xad, 0x5f, 0xae, 0x0e,
		0x4c, 0xb9, 0xfa, 0xe8, 0x69, 0xd2, 0x88, 0xc6, 0x4f,
		0x02, 0xb1, 0xcc, 0xba, 0x26, 0x42, 0x6f, 0xd4, 0x11,
		0xbc, 0xe7, 0x00, 0x80, 0xc7, 0x3c, 0x88, 0x81,
		0x02, 0xf6, 0xf0, 0xa3, 0x13, 0x4a, 0x26, 0xf0, 0x3e,
		0xf2, 0xe0, 0xde, 0xc5, 0x12, 0x34, 0x2f, 0x34,
		0x03, 0x03, 0x08
	};
	FILE *file;

	if (argc != 2)
		return 2;
	file = fopen(argv[1], "wb");
	if (file == NULL)
		return 1;
	if (fwrite(section, 1, sizeof(section), file) != sizeof(section) ||
	    fclose(file) != 0)
		return 1;
	return 0;
}
