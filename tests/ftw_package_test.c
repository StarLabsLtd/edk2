#include <stdint.h>
#include <stdio.h>
#include <string.h>

int main(int argc, char **argv)
{
	static const uint8_t header[24] = {
		0x76, 0xea, 0x5c, 0xfe, 0x72, 0x4f, 0xe8, 0x49,
		0x98, 0x6f, 0x2c, 0xd8, 0x99, 0xdf, 0xfe, 0x5d,
		0x59, 0xaa, 0x07, 0x00, 0x96, 0x80, 0x00, 0xf8
	};
	static const uint8_t depex[58] = {
		0x3a, 0x00, 0x00, 0x13, 0x02, 0xa9, 0x4f, 0x64, 0x8f, 0x50, 0xe8, 0xb1,
		0x4d, 0x9c, 0xe2, 0x0b, 0x44, 0x69, 0x8e, 0x8d, 0xa4, 0x02, 0xe1, 0xb4,
		0xdf, 0xb7, 0x2f, 0x05, 0x9f, 0x44, 0x87, 0xbe, 0x98, 0x18, 0xfc, 0x91,
		0xb7, 0x33, 0x02, 0xf6, 0xf0, 0xa3, 0x13, 0x4a, 0x26, 0xf0, 0x3e, 0xf2,
		0xe0, 0xde, 0xc5, 0x12, 0x34, 0x2f, 0x34, 0x03, 0x03, 0x08
	};
	uint8_t file[32918];
	FILE *input;

	if (argc != 2 || (input = fopen(argv[1], "rb")) == NULL ||
	   fread(file, 1, sizeof(file), input) != sizeof(file) || fgetc(input) != EOF ||
	   fclose(input) != 0)
		return 1;
	if (memcmp(file, header, sizeof(header)) ||
	   memcmp(file + sizeof(header), depex, sizeof(depex)) ||
	   file[0x54] != 0x04U || file[0x57] != 0x10U ||
	   file[0x58] != 'M' || file[0x59] != 'Z')
		return 1;
	return 0;
}
